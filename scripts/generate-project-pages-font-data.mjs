#!/usr/bin/env node
// One-off/rerun-on-change codegen: reads the extracted woff2 files under
// src/renderer/lib/projectPages/fonts/ and writes a plain TS module of
// base64 strings that render.tsx imports directly. This sidesteps runtime
// path resolution entirely (import.meta.url is empty once esbuild bundles
// to CJS, and __dirname/__filename differ between the TS source location
// and the bundled dist/ output) — a checked-in generated module resolves
// identically under vitest and under the esbuild bundle, since both just
// see plain exported string constants with no filesystem access needed at
// render time.
//
// Rerun with `node scripts/generate-project-pages-font-data.mjs` if the
// font files under fonts/ change.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const FONTS_DIR = join(REPO_ROOT, 'src/renderer/lib/projectPages/fonts');
const OUT_FILE = join(REPO_ROOT, 'src/renderer/lib/projectPages/library/fontData.ts');

function main() {
  const files = readdirSync(FONTS_DIR).filter(f => f.endsWith('.woff2')).sort();
  const entries = files.map(f => {
    const base64 = readFileSync(join(FONTS_DIR, f)).toString('base64');
    return `  '${f}': '${base64}',`;
  });
  const contents = `// Generated by scripts/generate-project-pages-font-data.mjs — do not hand-edit.
// Base64-encoded woff2 bytes for the fonts extracted from the saved
// component library's bundle manifest (see
// session-manager-operations/design-mocks/project-pages-component-library/README.md).
// Source files: src/renderer/lib/projectPages/fonts/*.woff2

export const FONT_DATA: Record<string, string> = {
${entries.join('\n')}
};
`;
  writeFileSync(OUT_FILE, contents);
  console.log(`Wrote ${OUT_FILE} (${files.length} fonts)`);
}

main();
