#!/usr/bin/env node
// Generates the two shipped Project Pages assets that live under
// src/main/templates/ (already covered by package.json's `files` → `src/main/`
// entry, alongside project-pages-default-home.html):
//
//   project-pages-catalog.json   — machine-readable component-library catalog:
//                                  every lens → slot → variant with its prose
//                                  `note`, DERIVED from
//                                  src/renderer/lib/projectPages/library/*.tsx
//                                  by bundling + evaluating them with esbuild,
//                                  never hand-transcribed.
//   project-pages-pipeline.md    — byte-for-byte copy of
//                                  session-manager-operations/architecture/
//                                  project-pages-pipeline.md, so a foreign
//                                  machine can read the contract without this
//                                  repo checked out.
//
// Both are COMMITTED files. Run `npm run build:project-pages-assets` whenever
// the library or the spec changes and commit the result;
// scripts/project-pages-publish-gate.cjs regenerates + compares them and fails
// the publish on drift, so forgetting to re-run this cannot ship silently.
//
// Repo-side build tool (needs the esbuild devDependency) — not in the tarball.
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const CATALOG_REL = 'src/main/templates/project-pages-catalog.json';
const SPEC_REL = 'session-manager-operations/architecture/project-pages-pipeline.md';
const SPEC_COPY_REL = 'src/main/templates/project-pages-pipeline.md';
const LIBRARY_ENTRY_REL = 'src/renderer/lib/projectPages/library/index.ts';

/**
 * Bundle the library entry in-memory (no externals: react/jsx-runtime is
 * inlined so evaluation needs nothing from the caller's require path) and
 * evaluate it to obtain LENS_LIBRARY / LENS_ORDER straight from the .tsx
 * sources.
 */
function loadLibrary(repoRoot) {
  // Lazy: esbuild is a devDependency and this file is required by the gate's
  // unit test — keep the import off the module's top level so a require()
  // without esbuild still gives a targeted error from here.
  const esbuild = require('esbuild');
  const entry = path.join(repoRoot, LIBRARY_ENTRY_REL);
  if (!fs.existsSync(entry)) throw new Error(`library entry not found: ${entry}`);
  const result = esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    write: false,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    jsx: 'automatic',
    logLevel: 'silent',
    absWorkingDir: repoRoot,
  });
  const code = result.outputFiles[0].text;
  const module = { exports: {} };
  const fn = vm.runInThisContext(`(function (module, exports, require) {${code}\n})`, {
    filename: 'project-pages-library.bundle.cjs',
  });
  fn(module, module.exports, require);
  const { LENS_LIBRARY, LENS_ORDER } = module.exports;
  if (!LENS_LIBRARY || !Array.isArray(LENS_ORDER)) {
    throw new Error(`${LIBRARY_ENTRY_REL} did not export LENS_LIBRARY + LENS_ORDER`);
  }
  return { LENS_LIBRARY, LENS_ORDER };
}

/** Pure projection: strip the React components, keep ids/labels/notes. */
function toCatalog({ LENS_LIBRARY, LENS_ORDER }) {
  return {
    $comment:
      'GENERATED by scripts/project-pages-assets.cjs from src/renderer/lib/projectPages/library/*.tsx — do not edit; run `npm run build:project-pages-assets`.',
    lenses: LENS_ORDER.map((lensId) => {
      const lens = LENS_LIBRARY[lensId];
      return {
        id: lens.id,
        label: lens.label,
        blurb: lens.blurb,
        slots: lens.slots.map((slot) => ({
          id: slot.id,
          label: slot.label,
          variants: slot.variants.map((v) => ({ id: v.id, label: v.label, note: v.note })),
        })),
        presets: lens.presets.map((p) => ({ id: p.id, label: p.label, note: p.note, pick: p.pick })),
      };
    }),
  };
}

function buildCatalog(repoRoot) {
  return toCatalog(loadLibrary(repoRoot));
}

function serializeCatalog(catalog) {
  return `${JSON.stringify(catalog, null, 2)}\n`;
}

function readSpec(repoRoot) {
  return fs.readFileSync(path.join(repoRoot, SPEC_REL), 'utf8');
}

function writeAssets(repoRoot) {
  const catalogPath = path.join(repoRoot, CATALOG_REL);
  const specCopyPath = path.join(repoRoot, SPEC_COPY_REL);
  fs.writeFileSync(catalogPath, serializeCatalog(buildCatalog(repoRoot)));
  fs.writeFileSync(specCopyPath, readSpec(repoRoot));
  return { catalogPath, specCopyPath };
}

function main() {
  const repoRoot = path.resolve(__dirname, '..');
  const { catalogPath, specCopyPath } = writeAssets(repoRoot);
  console.log(`Wrote ${path.relative(repoRoot, catalogPath)} and ${path.relative(repoRoot, specCopyPath)}`);
}

module.exports = {
  CATALOG_REL,
  SPEC_REL,
  SPEC_COPY_REL,
  buildCatalog,
  serializeCatalog,
  readSpec,
  writeAssets,
};

if (require.main === module) {
  try {
    main();
  } catch (err) {
    console.error(`project-pages-assets: ${err.message}`);
    process.exit(1);
  }
}
